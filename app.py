"""UrbanKart Customer Intelligence Hub - Streamlit entry point.

Run from the project root:
    python -m streamlit run app.py

Keep these files in the project root:
    app.py
    2_Customer_Feedback_Analysis.py
    urbankart_best_regression_model.joblib
    revenue_features.pkl
    requirements.txt
"""

from pathlib import Path
import logging

import joblib
import pandas as pd
import streamlit as st

ROOT_DIR = Path(__file__).resolve().parent
MODEL_PATH = ROOT_DIR / "urbankart_best_regression_model.joblib"
FEATURES_PATH = ROOT_DIR / "revenue_features.pkl"

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

st.set_page_config(
    page_title="UrbanKart Customer Intelligence Hub",
    page_icon="🛍️",
    layout="wide",
    initial_sidebar_state="expanded",
)

st.markdown(
    """
    <style>
      .main .block-container {padding-top: 1.6rem; padding-bottom: 2.5rem;}
      .hero {
        padding: 1.3rem 1.5rem; border-radius: 16px;
        background: linear-gradient(120deg, #14213d 0%, #254b75 100%);
        color: white; margin-bottom: 1rem;
      }
      .hero h1 {color: white; margin: 0 0 .3rem 0; font-size: 2rem;}
      .hero p {color: #e8f0fb; margin: 0;}
      div[data-testid="stMetric"] {
        border: 1px solid rgba(128,128,128,.22);
        border-radius: 12px; padding: 14px 16px;
      }
    </style>
    """,
    unsafe_allow_html=True,
)


@st.cache_resource(show_spinner="Loading the saved revenue model…")
def load_revenue_artifacts():
    """Load the regression model and feature list once per app process."""
    if not MODEL_PATH.is_file():
        raise FileNotFoundError(
            f"Required model file not found: {MODEL_PATH.name}. "
            "Place it in the project root; do not put it in a subfolder."
        )
    if not FEATURES_PATH.is_file():
        raise FileNotFoundError(
            f"Required feature file not found: {FEATURES_PATH.name}. "
            "Place it in the project root beside app.py."
        )
    model = joblib.load(MODEL_PATH)
    feature_columns = joblib.load(FEATURES_PATH)
    if not isinstance(feature_columns, (list, tuple, pd.Index)):
        raise TypeError("revenue_features.pkl must contain a list of training feature names.")
    return model, list(feature_columns)


def revenue_prediction_page():
    """Revenue prediction page; model artifacts are cached across reruns."""
    st.markdown(
        """
        <div class="hero">
          <h1>🛍️ UrbanKart Customer Intelligence Hub</h1>
          <p>Revenue Prediction · Estimate annual customer revenue from profile and behaviour</p>
        </div>
        """,
        unsafe_allow_html=True,
    )
    st.write(
        "Complete the customer profile and select **Predict Annual Revenue**. "
        "The estimate is generated by the saved regression model."
    )

    try:
        model, feature_columns = load_revenue_artifacts()
    except Exception as exc:
        st.error("The revenue model could not be loaded.")
        st.warning(
            "Required root-level files: `urbankart_best_regression_model.joblib` "
            "and `revenue_features.pkl`."
        )
        st.code(
            "KPMG/\n"
            "├── app.py\n"
            "├── 2_Customer_Feedback_Analysis.py\n"
            "├── urbankart_best_regression_model.joblib\n"
            "├── revenue_features.pkl\n"
            "└── requirements.txt",
            language="text",
        )
        logger.exception("Revenue model loading failed")
        st.exception(exc)
        return

    with st.form("revenue_prediction_form"):
        st.subheader("1. Customer profile")
        c1, c2, c3 = st.columns(3)
        with c1:
            age = st.number_input("Age", min_value=18, max_value=100, value=30)
            gender = st.selectbox("Gender", ["Female", "Male"])
            city_tier = st.selectbox("City Tier", ["Tier 1", "Tier 2", "Tier 3"])
        with c2:
            income = st.number_input("Annual Income (₹)", min_value=0.0, value=500000.0, step=10000.0)
            tenure = st.number_input("Customer Tenure (Months)", min_value=0, value=24)
            acquisition = st.selectbox(
                "Acquisition Channel",
                ["Offline Store", "Organic Search", "Affiliate", "Social Media",
                 "Paid Ads", "Referral", "Email Marketing"],
            )
        with c3:
            preferred_category = st.selectbox(
                "Preferred Category",
                ["Electronics", "Fashion", "Grocery", "Home", "Beauty", "Books", "Sports & Fitness"],
            )
            preferred_channel = st.selectbox(
                "Preferred Channel", ["Website", "Mobile App", "Physical Store", "Marketplace"]
            )

        st.subheader("2. Engagement and purchase behaviour")
        c1, c2, c3 = st.columns(3)
        with c1:
            website_visits = st.number_input("Monthly Website Visits", min_value=0, value=10)
            app_sessions = st.number_input("Monthly App Sessions", min_value=0, value=10)
            purchase_frequency = st.number_input("Monthly Purchase Frequency", min_value=0.0, value=3.0, step=1.0)
            average_order_value = st.number_input("Average Order Value (₹)", min_value=0.0, value=2000.0, step=100.0)
        with c2:
            discount_usage = st.number_input("Discount Usage Rate", min_value=0.0, max_value=1.0, value=0.2)
            orders_last_12m = st.number_input("Orders in Last 12 Months", min_value=0, value=20)
            days_since_purchase = st.number_input("Days Since Last Purchase", min_value=0, value=15)
            return_rate = st.number_input("Return Rate", min_value=0.0, max_value=1.0, value=0.05)
        with c3:
            loyalty_points = st.number_input("Loyalty Points", min_value=0, value=500)
            marketing_response = st.number_input("Marketing Response Rate", min_value=0.0, max_value=1.0, value=0.2)
            payment_delays = st.number_input("Payment Delay Count", min_value=0, value=0)
            support_tickets = st.number_input("Support Tickets (Last 12 Months)", min_value=0, value=1)

        st.subheader("3. Satisfaction and retention")
        c1, c2, c3 = st.columns(3)
        with c1:
            satisfaction = st.number_input("Customer Satisfaction Score", min_value=0.0, max_value=5.0, value=4.0)
        with c2:
            churn = st.selectbox("Customer Churn Status", [0, 1], format_func=lambda x: "No" if x == 0 else "Yes")
        with c3:
            purchase_next = st.selectbox(
                "Purchase Expected in Next 30 Days", [1, 0],
                format_func=lambda x: "Yes" if x == 1 else "No",
            )

        submitted = st.form_submit_button("Predict Annual Revenue", type="primary", use_container_width=True)

    if submitted:
        raw_customer = pd.DataFrame([{
            "Age": age,
            "Gender": gender,
            "City_Tier": city_tier,
            "Income": income,
            "Customer_Tenure_Months": tenure,
            "Acquisition_Channel": acquisition,
            "Website_Visits_Monthly": website_visits,
            "App_Sessions_Monthly": app_sessions,
            "Purchase_Frequency_Monthly": purchase_frequency,
            "Average_Order_Value": average_order_value,
            "Discount_Usage_Rate": discount_usage,
            "Orders_Last_12M": orders_last_12m,
            "Days_Since_Last_Purchase": days_since_purchase,
            "Return_Rate": return_rate,
            "Support_Tickets_12M": support_tickets,
            "Customer_Satisfaction_Score": satisfaction,
            "Payment_Delay_Count": payment_delays,
            "Loyalty_Points": loyalty_points,
            "Marketing_Response_Rate": marketing_response,
            "Churn": churn,
            "Purchase_Next_30_Days": purchase_next,
            "Preferred_Category": preferred_category,
            "Preferred_Channel": preferred_channel,
        }])

        try:
            encoded_customer = pd.get_dummies(raw_customer, drop_first=True, dtype=int)
            encoded_customer = encoded_customer.reindex(columns=feature_columns, fill_value=0)
            prediction = float(model.predict(encoded_customer)[0])
            st.divider()
            st.subheader("Prediction result")
            m1, m2 = st.columns(2)
            m1.metric("Estimated Annual Revenue", f"₹{prediction:,.2f}")
            m2.metric("Loaded model", MODEL_PATH.name)
            st.caption(
                "This is a model estimate, not a guarantee of actual future revenue. "
                "Prediction quality depends on training data and matching feature definitions."
            )
        except Exception as exc:
            logger.exception("Revenue prediction failed")
            st.error(
                "Prediction failed. Confirm that `revenue_features.pkl` matches the model "
                "and that the model was trained with the same dummy-encoding convention."
            )
            st.exception(exc)


revenue_page = st.Page(
    revenue_prediction_page,
    title="Revenue Prediction",
    icon="💰",
    default=True,
)
feedback_page = st.Page(
    str(ROOT_DIR / "2_Customer_Feedback_Analysis.py"),
    title="Customer Feedback Analysis",
    icon="💬",
)

navigation = st.navigation(
    {
        "Customer Intelligence": [revenue_page, feedback_page],
    },
    position="sidebar",
)
navigation.run()
